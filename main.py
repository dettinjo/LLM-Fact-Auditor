from src.fact_check import FactCheck

def parse_question(text):
    """
    Parse the input file, breaks down each line into question ID and question, and saves them in a dictionary    
    
    Args:
    text: Content of the input file.
    
    Returns:
    dict: A dictionary with question IDs as keys and questions as values.
    """
    question_dict = {}
    lines = text.split("\n")
    lines = [x+"\n" for x in lines if x]

    for line in lines:
        # split "Q1<TAB>string"
        key_value = line.strip().split("\t")
        
        if len(key_value) == 2:
            key, value = key_value
            question_dict[key] = {'Q': value}
    return question_dict



def generate_entity(question, response) -> list[Entity]:
    """
    Generates entity links from a given question and its response.
    
    Args:
    question (str): The original question.
    response (str): The response generated by the model.
    
    Returns:
    list: all entities recognized list[Entity]
    """
    el = EntityLinking(50)
    text = question + " " + response
    entities = el.link(text)

    return entities

def generate_all_answer(question_dict, llama_wrapper:LlamaWrapper):
    """
    Processes all questions to generate responses and entity links, and save them in the dictionary.
    
    Args:
    question_dict (dict): Dictionary containing questions.
    
    Returns:
    dict: Updated dictionary with responses and entity links.
    """
    for question_id in question_dict.keys():
        question = question_dict[question_id]['Q']
        # get response from llama model
        response = llama_wrapper.generate(question)
        question_dict[question_id]['R'] = response
        # entity linking
        entities = generate_entity(question, response)
        question_dict[question_id]['E'] = entities
    return question_dict

def post_process(question_dict):
    """
    generate a clear answer and check the correctness of answer
    """

    classifier = QuestionClassifier()
    concluder = Conclusion()
    statement =  Statement()
    fact =  FactCheck()
    relation = RelationTriple()

    for question_id in question_dict.keys():
        question = question_dict[question_id]['Q']
        response = question_dict[question_id]['R']
        entities = question_dict[question_id]['E']
        # entity_dict = {entity.mention: entity.get_wikipedia_page() for entity in entities}
        if 'Question:' in question:
            question = question.replace('Question:', '').strip()
        if 'Answer:' in question:
            question = question.replace('Answer:', '').strip()

        # classify question as entity, yes/no, statement, and generate answer from model response
        question_type = classifier.classify(question)
        if question_type in [QUESTION_TYPE_STATEMENT, QUESTION_TYPE_BOOLEAN]:
            answer = concluder.conclude_yn(question, response)
            question_dict[question_id]['A'] = answer 
        else:
            concluded_entity = concluder.conclude_entity(question,question+" "+response,entities)
            wiki_link = concluded_entity.wikipedia_link
            question_dict[question_id]['A'] = wiki_link
            answer = concluded_entity.mention
        
        

        state = statement.construct_statement(question_type, question, answer)
        
        triple, subject, obj = relation.get_triples(state, entities)
        if subject and obj: # if triplet has entities as subject and object
            check_ans = fact.if_triple_exists(triple, subject, obj)
            if question_type == QUESTION_TYPE_BOOLEAN or question_type == QUESTION_TYPE_STATEMENT:
                if (answer=='yes' and check_ans is True) or (answer=='no' and check_ans is False):
                    correctness = 'correct'
                else:
                    correctness = 'incorrect'
            else:
                if check_ans is True:
                    correctness = 'correct'
                else:
                    correctness = 'incorrect'
        else: # for questions that has no relation triple like <E, relation(str), E> 
            if question_type == QUESTION_TYPE_BOOLEAN or question_type == QUESTION_TYPE_STATEMENT:
                if fact.fact_check_yn_using_concluder(question, response, answer, entities):
                    correctness = 'correct'
                else:
                    correctness = 'incorrect'
            else:
                if fact.fact_check_entity_using_concluder(question, response, state, concluded_entity):
                    correctness = 'correct'
                else:
                    correctness = 'incorrect'
        question_dict[question_id]['C'] = correctness
    
    return question_dict

def format_output(output_dict):
    """
    Formats the output dictionary into a string suitable for saving to a file.
    
    Args:
    output_dict (dict): The dictionary containing questions, responses, and entity links.
    
    Returns:
    str: A formatted string representing the output data.
    """    
    output = ""

    for i in output_dict.keys():
        output += (f"{i}\tR\"{output_dict[i]['R']}\"\n")
        output += (f"{i}\tA\"{output_dict[i]['A']}\"\n")
        output += (f"{i}\tC\"{output_dict[i]['C']}\"\n")
        for entity in output_dict[i]['E']:
            output += (f"{i}\tE\"{entity.mention}\"\t\"{entity.get_wikipedia_page()}\"\n")

    output = output.strip()

    return output

def main_task(input, llama_wrapper:LlamaWrapper):
    """
    Integrate all processes of all tasks

    Args:
    input_path (str): Path to the input file containing questions.
    output_path (str): Path to the output file.
    """
    
    # read questions into a dictionary
    question_dict = parse_question(input)
    # append response and entity linking into the dictionary
    ret_dict = generate_all_answer(question_dict, llama_wrapper)
    ret_dict = post_process(ret_dict)

    return format_output(ret_dict)

